// node --test tools/
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { UnsupportedSchema, docComment, generate, typeOf, wrap } from "./protocol-types.ts";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = "crates/protocol/schema.json";

test("sdk/src/protocol.ts is current with the committed schema", () => {
  const schema = JSON.parse(readFileSync(resolve(REPO, SCHEMA), "utf8"));
  const committed = readFileSync(resolve(REPO, "sdk/src/protocol.ts"), "utf8");
  assert.ok(generate(schema, SCHEMA) === committed, "sdk/src/protocol.ts is out of date; run `make protocol`");
});

test("scalars, refs, consts and nullable types", () => {
  assert.equal(typeOf(true, "#"), "unknown");
  assert.equal(typeOf({ default: null }, "#"), "unknown");
  assert.equal(typeOf({ type: "integer", format: "uint64", minimum: 0 }, "#"), "number");
  assert.equal(typeOf({ type: ["integer", "null"], format: "uint64" }, "#"), "number | null");
  assert.equal(typeOf({ $ref: "#/$defs/Sender" }, "#"), "Sender");
  assert.equal(typeOf({ const: "request", type: "string" }, "#"), '"request"');
  assert.equal(typeOf({ enum: ["a", "b"], type: "string" }, "#"), '"a" | "b"');
  assert.equal(typeOf({ anyOf: [{ $ref: "#/$defs/X" }, { type: "null" }] }, "#"), "X | null");
  assert.equal(typeOf({ type: "array", items: { type: "string" } }, "#"), "string[]");
  assert.equal(
    typeOf({ type: "array", prefixItems: [{ type: "string" }, { $ref: "#/$defs/Direction" }], minItems: 2, maxItems: 2 }, "#"),
    "[string, Direction]",
  );
  assert.throws(() => typeOf({ type: "array", prefixItems: [true], items: true }, "#"), UnsupportedSchema);
  assert.equal(typeOf({ type: "array", items: { anyOf: [{ type: "string" }, { type: "null" }] } }, "#"), "Array<string | null>");
});

test("objects: required fields first in declaration order, the rest optional", () => {
  const schema = {
    type: "object",
    properties: { b: { type: "string" }, a: { type: "boolean" }, kind: { const: "x" }, "two words": true },
    required: ["kind", "b"],
  };
  assert.equal(typeOf(schema, "#"), '{ kind: "x"; b: string; a?: boolean; "two words"?: unknown }');
  assert.equal(typeOf({ type: "object", additionalProperties: true }, "#"), "Record<string, unknown>");
  assert.equal(typeOf({ type: "object", additionalProperties: { type: "number" } }, "#"), "Record<string, number>");
});

test("documented fields and variants are laid out one per line", () => {
  const schema = {
    oneOf: [
      { description: "First.", type: "object", properties: { n: { type: "integer", description: "A count." } }, required: ["n"] },
      { type: "null" },
    ],
  };
  assert.equal(typeOf(schema, "#"), "\n  /** First. */\n  | {\n    /** A count. */\n    n: number;\n  }\n  | null");
});

test("anything the generator doesn't understand is an error, not `unknown`", () => {
  for (const bad of [
    { type: "string", pattern: "^a" },
    { allOf: [] },
    { $ref: "other.json#/X" },
    { type: "object", properties: { a: true }, additionalProperties: true },
    { type: "object", properties: {}, required: ["missing"] },
    { items: { type: "string" } },
  ]) {
    assert.throws(() => typeOf(bad, "#/x"), UnsupportedSchema, JSON.stringify(bad));
  }
  assert.throws(() => generate({ $defs: { "not-a-name": true } }, "s"), UnsupportedSchema);
});

test("comments wrap at word boundaries and can't end early", () => {
  assert.deepEqual(wrap("aa bb cc", 5), ["aa bb", "cc"]);
  assert.deepEqual(wrap("one\n\ntwo", 80), ["one", "", "two"]);
  assert.equal(docComment("Short."), "/** Short. */\n");
  assert.equal(docComment("a */ b"), "/** a *\\/ b */\n");
  assert.equal(docComment(undefined), "");
  assert.equal(docComment("x".repeat(60) + " " + "y".repeat(60)), `/**\n * ${"x".repeat(60)}\n * ${"y".repeat(60)}\n */\n`);
});

test("constants and types become exports", () => {
  const out = generate(
    { description: "Frames.", "x-constants": { BROKER: { value: "bus", description: "Name." } }, $defs: { Id: { type: "integer" } } },
    "s.json",
  );
  assert.match(out, /^\/\/ Generated by tools\/gen-protocol.ts from s.json/);
  assert.match(out, /\/\/ Frames\.\n/);
  assert.match(out, /\/\*\* Name\. \*\/\nexport const BROKER = "bus";/);
  assert.match(out, /export type Id = number;/);
});

test("fields beside a union (a struct flattening an enum) are joined to it", () => {
  const schema = {
    type: "object",
    anyOf: [{ $ref: "#/$defs/DataRule" }, { $ref: "#/$defs/CapabilityRule" }],
    properties: { id: { type: "integer" }, app: { type: "string" } },
    required: ["id", "app"],
  };
  assert.equal(typeOf(schema, "#"), "{ id: number; app: string } & (DataRule | CapabilityRule)");
});
